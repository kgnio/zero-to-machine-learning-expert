
# Stage 02 - Lesson 01: Data Structures

# List: Ordered and mutable
scores = [85, 100, 76, 85]
scores.append(95)

print("List:", scores)

# Tuple: Ordered and immutable
coordinates = (10, 20)

print("Tuple:", coordinates)

# Set: Contains unique elements
categories = {"Math", "Science", "Math", "English", "Physics", "Physics"}

print("Set:", sorted(categories))

# Dictionary: Stores key-value pairs
student = {
    "name": "Alice",
    "age": 21,
    "score": 85,
    "city": "London"
}

print("Dictionary:", student)
